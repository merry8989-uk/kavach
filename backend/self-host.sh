#!/usr/bin/env bash
#
# Run your own Kavach server, in one command.
#
#   ./self-host.sh              # set up and start
#   ./self-host.sh status       # what is running, and is it healthy
#   ./self-host.sh token        # print the token to paste into the app
#   ./self-host.sh logs         # follow the API log
#   ./self-host.sh stop         # stop, keeping the database
#   ./self-host.sh destroy      # stop and DELETE the database (asks first)
#
# What it does, in order:
#   1. checks Docker is actually available and usable
#   2. generates strong secrets, because a server with a guessable token is
#      worse than no server — it looks protected
#   3. writes backend/.env with mode 600, never overwriting an existing one
#   4. builds and starts Postgres + Redis + the API
#   5. waits for /health/ready, which is the endpoint that also proves Postgres
#      is reachable, then prints what to paste into the app
#
# It is deliberately chatty. A self-host setup that fails silently and tells you
# to "check the logs" has not helped anyone.

set -euo pipefail

cd "$(dirname "$0")"

COMPOSE_FILE="docker-compose.selfhost.yml"
ENV_FILE=".env"
GREEN=$'\033[0;32m'; YELLOW=$'\033[1;33m'; RED=$'\033[0;31m'; BOLD=$'\033[1m'; OFF=$'\033[0m'

say()  { printf '%s\n' "$*"; }
ok()   { printf '%s✓%s %s\n' "$GREEN" "$OFF" "$*"; }
warn() { printf '%s!%s %s\n' "$YELLOW" "$OFF" "$*"; }
die()  { printf '%s✗%s %s\n' "$RED" "$OFF" "$*" >&2; exit 1; }

# ---------------------------------------------------------------- compose --

# Docker Compose v2 ships as `docker compose`; v1 as `docker-compose`. Both are
# still in the wild, and guessing wrong produces a confusing error.
compose() {
  if docker compose version >/dev/null 2>&1; then
    docker compose -f "$COMPOSE_FILE" "$@"
  elif command -v docker-compose >/dev/null 2>&1; then
    docker-compose -f "$COMPOSE_FILE" "$@"
  else
    die "Docker Compose not found. Install Docker Desktop, or the docker-compose-plugin package."
  fi
}

require_docker() {
  command -v docker >/dev/null 2>&1 || die "Docker is not installed. See https://docs.docker.com/get-docker/"
  docker info >/dev/null 2>&1 || die "Docker is installed but not running (or you lack permission to use it).
  - Start Docker Desktop, or
  - on Linux: sudo systemctl start docker, and add yourself to the docker group."
}

# ---------------------------------------------------------------- secrets --

secret() {
  # python3 is already required by this project; openssl is a fallback.
  if command -v python3 >/dev/null 2>&1; then
    python3 -c "import secrets,sys; print(secrets.token_urlsafe(int(sys.argv[1])))" "$1"
  elif command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 "$1" | tr -d '\n=+/' | cut -c1-"$((1 + $1 * 4 / 3))"
  else
    die "Neither python3 nor openssl is available to generate secrets."
  fi
}

write_env() {
  if [ -f "$ENV_FILE" ]; then
    ok "$ENV_FILE already exists — leaving it alone."
    say "  (To start over with fresh secrets: delete $ENV_FILE and run this again.)"
    return
  fi

  say "Generating secrets…"
  local api_token phone_pepper jwt_secret db_password
  api_token=$(secret 48)
  phone_pepper=$(secret 48)
  jwt_secret=$(secret 48)
  db_password=$(secret 24)

  # umask before the redirect, so the file is never briefly world-readable.
  ( umask 077; cat > "$ENV_FILE" <<EOF
# Kavach self-hosted server — generated by self-host.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
#
# Treat this file as a secret. It is already mode 600 and listed in .gitignore.
# Changing PHONE_PEPPER invalidates every stored number hash.
# Changing JWT_SECRET signs every user out.

ENVIRONMENT=production

POSTGRES_USER=kavach
POSTGRES_PASSWORD=$db_password
POSTGRES_DB=kavach

# The bootstrap token. This is the value you paste into the app, and the app
# ships it in the APK — so it is a registration key, not an API key. Everything
# after registration uses the per-install token the app is given back.
API_TOKEN=$api_token
ALLOW_SHARED_TOKEN=false

PHONE_PEPPER=$phone_pepper
JWT_SECRET=$jwt_secret

API_PORT=8000
API_BIND=127.0.0.1
RATE_LIMIT_PER_MINUTE=60
SCORING_RULE_VERSION=2026-01

# Sign-in needs an SMS provider. Left as none, the OTP endpoint returns 503
# rather than pretending to send a code.
SMS_PROVIDER=none
SMS_API_KEY=
SMS_SENDER_ID=
SMS_TEMPLATE_ID=
SMS_ACCOUNT_SID=
SMS_FROM=

# Leave unset and the AI endpoints return 503 rather than inventing a result.
ASR_PROVIDER_URL=
ASR_PROVIDER_KEY=
LLM_PROVIDER_URL=
LLM_PROVIDER_KEY=
EOF
  )
  chmod 600 "$ENV_FILE"
  ok "Wrote $ENV_FILE (mode 600) with fresh secrets."
}

# ------------------------------------------------------------------ wait --

wait_for_health() {
  say "Waiting for the API to report healthy…"
  local port url tries=0 max=60
  port=$(grep -E '^API_PORT=' "$ENV_FILE" 2>/dev/null | cut -d= -f2)
  port=${port:-8000}
  url="http://127.0.0.1:${port}/health/ready"

  while [ "$tries" -lt "$max" ]; do
    if curl -fsS "$url" >/dev/null 2>&1; then
      ok "Healthy."
      return 0
    fi
    # A container that has already exited will never become healthy, so say so
    # now rather than after a minute of waiting.
    if ! compose ps --status running 2>/dev/null | grep -q api; then
      warn "The API container is not running. Its log:"
      compose logs --tail 40 api || true
      die "Start-up failed. The message above usually names the missing setting."
    fi
    tries=$((tries + 1))
    printf '.'
    sleep 2
  done
  printf '\n'
  compose logs --tail 40 api || true
  die "The API did not become healthy within $((max * 2))s."
}

print_token() {
  [ -f "$ENV_FILE" ] || die "No $ENV_FILE yet — run ./self-host.sh first."
  local port token
  port=$(grep -E '^API_PORT=' "$ENV_FILE" | cut -d= -f2); port=${port:-8000}
  token=$(grep -E '^API_TOKEN=' "$ENV_FILE" | cut -d= -f2-)

  say ""
  say "${BOLD}Paste these into Kavach → Settings → Self-hosted lookup${OFF}"
  say ""
  say "  Server URL   http://<this-machine-ip>:${port}"
  say "  API token    ${token}"
  say ""
  say "On this machine the URL is http://127.0.0.1:${port}."
  say "From a phone on the same Wi-Fi, use this machine's LAN address:"
  say "  Linux   hostname -I | awk '{print \$1}'"
  say "  macOS   ipconfig getifaddr en0"
  say ""
}

# ------------------------------------------------------------------ main --

case "${1:-up}" in
  up|start|"")
    require_docker
    write_env
    say "Building the image (first run takes a few minutes)…"
    compose build
    say "Starting Postgres, Redis and the API…"
    compose up -d
    wait_for_health
    print_token
    say "Useful next:"
    say "  ./self-host.sh logs     follow the API log"
    say "  ./self-host.sh status   what is running"
    say "  ./self-host.sh token    print the token again"
    ;;

  status)
    require_docker
    compose ps
    port=$(grep -E '^API_PORT=' "$ENV_FILE" 2>/dev/null | cut -d= -f2); port=${port:-8000}
    if curl -fsS "http://127.0.0.1:${port}/health/ready" 2>/dev/null; then
      say ""; ok "The API is healthy."
    else
      warn "The API is not answering on port ${port}."
    fi
    ;;

  token)
    print_token
    ;;

  logs)
    require_docker
    compose logs -f --tail 100 api
    ;;

  stop|down)
    require_docker
    compose down
    ok "Stopped. Your database is kept in the kavach_pgdata volume."
    ;;

  destroy)
    require_docker
    warn "This deletes the database volume — every stored number hash, report and"
    warn "consent record goes with it. There is no undo."
    printf 'Type "destroy" to confirm: '
    read -r reply
    [ "$reply" = "destroy" ] || die "Not confirmed. Nothing was deleted."
    compose down -v
    ok "Stopped and the database volume was removed."
    ;;

  *)
    say "Usage: ./self-host.sh [up|status|token|logs|stop|destroy]"
    exit 1
    ;;
esac
