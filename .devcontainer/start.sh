#!/usr/bin/env bash
#
# Start the Kavach server in a Codespace.
#
#   bash .devcontainer/start.sh              # run it
#   bash .devcontainer/start.sh --prepare-only   # migrate and stop
#
# Everything it needs is generated here rather than being asked for, because this
# is a throwaway environment and a prompt for a secret you are about to throw
# away is friction with nothing behind it. The values are written to
# `backend/.env` (mode 600, git-ignored) and printed once so you can point the
# Android app at this server.

set -euo pipefail

cd "$(dirname "$0")/.."
ROOT="$(pwd)"
ENV_FILE="$ROOT/backend/.env"

PREPARE_ONLY=0
[[ "${1:-}" == "--prepare-only" ]] && PREPARE_ONLY=1

say() { printf '\n\033[1m%s\033[0m\n' "$1"; }

# ---------------------------------------------------------------- the database --
say "Waiting for Postgres"
# The feature starts it, but not instantly, and a server that races its database
# on first boot fails in a way that looks like a code problem.
for _ in $(seq 1 30); do
  if pg_isready -q 2>/dev/null; then break; fi
  sleep 1
done
pg_isready || { echo "Postgres did not come up. Check the Postgres feature in devcontainer.json."; exit 1; }

sudo -u postgres psql -q -c "SELECT 1 FROM pg_database WHERE datname='kavach'" 2>/dev/null | grep -q 1 \
  || sudo -u postgres createdb kavach
sudo -u postgres psql -q -c "ALTER USER postgres PASSWORD 'postgres'" 2>/dev/null || true

# ------------------------------------------------------------------ the secrets --
if [[ -f "$ENV_FILE" ]]; then
  say "Keeping the existing backend/.env"
else
  say "Generating secrets"
  API_TOKEN="$(python3 -c 'import secrets; print(secrets.token_urlsafe(48))')"
  PHONE_PEPPER="$(python3 -c 'import secrets; print(secrets.token_urlsafe(32))')"
  JWT_SECRET="$(python3 -c 'import secrets; print(secrets.token_urlsafe(48))')"

  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by .devcontainer/start.sh. Throwaway values for a codespace.
ENVIRONMENT=development
DATABASE_URL=postgresql+psycopg://postgres:postgres@127.0.0.1:5432/kavach
API_TOKEN=$API_TOKEN
PHONE_PEPPER=$PHONE_PEPPER
JWT_SECRET=$JWT_SECRET
AUTO_CREATE_TABLES=false
ALLOW_SHARED_TOKEN=false
OTP_DEBUG_RETURN=false
EOF
  chmod 600 "$ENV_FILE"
  echo "  wrote $ENV_FILE (mode 600)"
fi

# ----------------------------------------------------------------- migrations --
say "Applying migrations"
cd "$ROOT/backend"
set -a; . "$ENV_FILE"; set +a
alembic upgrade head

if [[ "$PREPARE_ONLY" == "1" ]]; then
  say "Ready"
  echo "  Start it with:  bash .devcontainer/start.sh"
  exit 0
fi

# ------------------------------------------------------------------- the server --
TOKEN="$(grep '^API_TOKEN=' "$ENV_FILE" | cut -d= -f2-)"

say "Kavach server"
cat <<EOF
  Listening on 0.0.0.0:8000
  Public URL:  Ports tab → port 8000 → copy the forwarded address

  In the Android app:
    Settings → Self-hosted lookup
      Server URL:  <the forwarded address>
      Token:       $TOKEN

  Sign-in will answer 503 — no SMS provider is configured here, and the server
  starts anyway on purpose. Caller lookup and spam reputation work without one.
EOF

exec uvicorn app.main:app --host 0.0.0.0 --port 8000
